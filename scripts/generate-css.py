        f"0 {p(2)} {p(4)} {p(-2)} rgb(0 0 0 / 0.1);\n"
        f"  --shadow-lg: 0 {p(10)} {p(15)} {p(-3)} rgb(0 0 0 / 0.1), "
        f"0 {p(4)} {p(6)} {p(-4)} rgb(0 0 0 / 0.1);\n"
