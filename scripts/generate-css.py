        f"0 {p(8)} {p(10)} {p(-6)} rgb(0 0 0 / 0.1);\n"
        f"  --shadow-2xl: 0 {p(25)} {p(50)} {p(-12)} rgb(0 0 0 / 0.25);\n"
        f"  --shadow: 0 {px} {p(3)} 0 rgb(0 0 0 / 0.1), "
        f"0 {px} {p(2)} {p(-1)} rgb(0 0 0 / 0.1);\n"
